#!/usr/bin/env python3
"""Assemble/test one local partial source package; no network or source execution."""
import datetime
import gzip
import hashlib
import json
import pathlib
import shutil
import sys
import tarfile

root = pathlib.Path(sys.argv[1]).resolve()
assert root.parent == pathlib.Path("/tmp") and root.name.startswith("frr-task0004-bundle.")
stage = root / "staging"
name = "frr-route-reflector-v0.1.0-lab.1-sources.1-staging"
project_commit = "2920cfaed358f7166900eade1771acb1321be9e9"


def read(name):
    return json.loads((root / name).read_text())


def hash_file(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


meta = stage / "metadata"
meta.mkdir(exist_ok=True)
for item in ("materialization.json", "distributed-files.json", "notice-members.json", "additional-notices.json", "notice-gaps.json"):
    shutil.copyfile(root / item, meta / item)
facts = [{k: v for k, v in fact.items() if k != "header"} for fact in read("license-facts.json")]
(meta / "license-facts.json").write_text(json.dumps(facts, indent=2) + "\n")
shutil.copyfile(root / "source-bundle-reconstruction.md", stage / "RECONSTRUCT.md")
old = json.loads((stage / "project/docs/evidence/task0004-source-bundle-manifest.json").read_text())
images = read("distributed-files.json")["images"]
notes = {
    "alpine-keys": "BLOCKED generated key-data MIT attribution; fixed root COPYING probe 404, no holder fabricated",
    "alpine-base": "BLOCKED generated release-data MIT attribution; source generation is in APKBUILD, root COPYING 404",
    "apk-tools": "BLOCKED qualified libapk/OpenSSL distribution-basis question; NEEDED/source/grants preserved, no verified exception established",
    "ca-certificates": "MPL certdata and full MPL text retained; only bundle is installed, not c_rehash/update-ca tools. MIT generator headers retained; output attribution still reviewed",
    "frr": "Complete upstream archive plus doc/licenses and manual notice retained; installed code/config/YANG, no manual paths observed. Proposed GPLv3-compatible vtysh/Readline path, not blanket legal clearance",
    "elfutils": "Only libelf installed; selected library headers permit LGPL-3.0-or-later OR GPL-2.0-or-later; propose GPL-2.0-or-later, preserve original APK AND/OR expression and all three texts",
    "libcap": "libcap and libpsx installed; root and psx License expressly permit BSD-3-Clause OR GPL-2.0-only. Proposed BSD branch; original grants/copyright-bearing source retained",
    "zstd": "Only shared library installed; zstd.h and xxhash.h expressly allow BSD/GPL alternative. Proposed BSD branch, copyright-bearing headers and LICENSE retained",
    "musl": "getconf/getent BSD-2-Clause; iconv GPL-2.0-or-later; ldd generated by APKBUILD. libc MIT with original COPYRIGHT exceptions retained. ldconfig wrapper attribution remains BLOCKED",
}
matrix = []
for origin in old["origins"]:
    key = origin["origin"]
    prefix = "origins/" + key + "/" + origin["version"]
    material = [r for r in read("materialization.json")["files"] if r["path"].startswith(prefix + "/")]
    installed = {}
    for image in images:
        installed[image["architecture"]] = [p for p in image["packages"] if p["origin"] == key]
    notice = [n for n in read("notice-members.json") + read("additional-notices.json") if n["origin"] == key]
    expressions = sorted({p["declared_license"] for p in installed["amd64"]})
    matrix.append({"origin": key, "version": origin["version"], "aports_commit": origin["aports_commit"],
                   "packages": [p["name"] for p in installed["amd64"]], "declared_expressions": expressions,
                   "installed_file_paths": sorted({f["path"] for ps in installed.values() for p in ps for f in p["files"]}),
                   "installed_file_hashes": "metadata/distributed-files.json",
                   "local_prefix": prefix, "source_recipe_files": material, "notices": notice,
                   "material_result": "PASS frozen input/recipe bytes locally present and hashed",
                   "review": notes.get(key, "Recorded origin inputs, recipes and original notice members retained; no expanded source obligation inferred for permissive grants"),
                   "distribution_result": "BLOCKED pending final notice/delivery and global applicable-helper review"})
(meta / "origin-matrix.json").write_text(json.dumps(matrix, indent=2) + "\n")

files = []
for path in sorted(stage.rglob("*")):
    relative = str(path.relative_to(stage))
    if path.is_symlink():
        files.append({"path": relative, "kind": "symlink", "target": str(path.readlink())})
    elif path.is_file():
        files.append({"path": relative, "kind": "file", "bytes": path.stat().st_size, "sha256": hash_file(path)})
document = {"format": "task0004-local-partial-source-bundle-v1", "archive_root": name,
            "project_source_commit": project_commit, "project_binding": "PROVISIONAL; unmerged preparation commit",
            "accepted_main": "885e5c97e308b2b1442c378927613b2383dc6408",
            "images": [{k: i[k] for k in ("architecture", "local_id", "config_sha256")} for i in images],
            "scope": "173 frozen inputs + 180 recipe files + original/additional notices + provisional project source",
            "completeness": "BLOCKED; explicit generated-data/wrapper attribution, applicable external helper binding, legal/delivery review",
            "cve": "CVE scan NOT RUN — Owner explicitly omitted", "publication": "NOT AUTHORIZED / LOCAL ONLY", "files": files}
(stage / "MANIFEST.json").write_text(json.dumps(document, indent=2) + "\n")
total = sum(f.get("bytes", 0) for f in files) + (stage / "MANIFEST.json").stat().st_size
assert shutil.disk_usage(root).free > total + 192 * 1024**2, "STOP: archive free-space reserve"
archive = root / (name + ".tar.gz")
assert not archive.exists(), "Do not overwrite a staged artifact"
with archive.open("xb") as raw, gzip.GzipFile(fileobj=raw, filename="", mode="wb", mtime=0) as zipped:
    with tarfile.open(fileobj=zipped, mode="w|") as tar:
        for path in sorted(stage.rglob("*")):
            relative = str(path.relative_to(stage))
            info = tar.gettarinfo(str(path), arcname=name + "/" + relative)
            info.uid = info.gid = info.mtime = 0
            info.uname = info.gname = ""
            if info.isfile():
                with path.open("rb") as stream:
                    tar.addfile(info, stream)
            else:
                tar.addfile(info)

# Reopen/stream every member and verify content, safe paths and duplicate absence.
expected = {f["path"]: f for f in files}
seen = set()
with tarfile.open(archive) as tar:
    for member in tar:
        assert member.name.startswith(name + "/") and ".." not in pathlib.PurePosixPath(member.name).parts
        relative = member.name[len(name) + 1:]
        if member.isdir():
            continue
        assert relative not in seen
        seen.add(relative)
        if relative == "MANIFEST.json":
            assert json.load(tar.extractfile(member)) == document
        elif member.isfile():
            body = tar.extractfile(member)
            assert member.size == expected[relative]["bytes"]
            assert hashlib.file_digest(body, "sha256").hexdigest() == expected[relative]["sha256"]
        else:
            assert member.issym() and member.linkname == expected[relative]["target"]
            assert not pathlib.PurePosixPath(member.linkname).is_absolute() and ".." not in pathlib.PurePosixPath(member.linkname).parts
assert seen == set(expected) | {"MANIFEST.json"}
checksum = hash_file(archive)
(root / (archive.name + ".sha256")).write_text(checksum + "  " + archive.name + "\n")
result = {"artifact": archive.name, "sha256": checksum, "bytes": archive.stat().st_size,
          "manifest_sha256": hash_file(stage / "MANIFEST.json"), "file_records": len(files), "checked_members": len(seen),
          "payload_bytes_with_manifest": total, "materialization": {k: v for k, v in read("materialization.json").items() if k != "files"},
          "project_source_commit": project_commit, "project_binding": "PROVISIONAL",
          "images": document["images"], "original_notice_members": len(read("notice-members.json")),
          "additional_notice_files": len(read("additional-notices.json")), "technical_archive_validation": "PASS",
          "source_legal_completeness": "BLOCKED", "publication": "NOT AUTHORIZED / LOCAL ONLY",
          "cve": document["cve"], "timestamp_utc": datetime.datetime.now(datetime.timezone.utc).isoformat()}
(root / "bundle-result.json").write_text(json.dumps(result, indent=2) + "\n")
print(json.dumps(result, indent=2))
